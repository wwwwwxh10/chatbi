export type LocaleCode = 'zh-CN' | 'en-US'

const STORAGE_KEY = 'chatbi-preferences'

function readInitialLocale(): LocaleCode {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (!raw) return 'zh-CN'
    const parsed = JSON.parse(raw) as { state?: { locale?: LocaleCode } }
    const v = parsed?.state?.locale
    if (v === 'zh-CN' || v === 'en-US') return v
    return 'zh-CN'
  } catch {
    return 'zh-CN'
  }
}

